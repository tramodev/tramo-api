ALTER TABLE project ADD COLUMN restore_epoch bigint NOT NULL DEFAULT 0;
ALTER TABLE project ADD COLUMN history_unavailable boolean NOT NULL DEFAULT false;
ALTER TABLE project ADD COLUMN last_auto_version_date timestamp;
CREATE TABLE project_version (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    snapshot text NOT NULL,
    created_at timestamp NOT NULL,
    type varchar(16) NOT NULL CHECK (type IN ('AUTO', 'MANUAL', 'RESTORE')),
    name varchar(120),
    state_hash varchar(64) NOT NULL,
    snapshot_bytes bigint NOT NULL CHECK (snapshot_bytes > 0)
);
CREATE INDEX idx_project_version_history ON project_version(project_id, id DESC);
CREATE INDEX idx_project_version_auto ON project_version(project_id, type, id DESC);
CREATE TABLE editor_image_version_reference (
    version_id bigint NOT NULL REFERENCES project_version(id) ON DELETE CASCADE,
    image_id uuid NOT NULL REFERENCES editor_image(id),
    PRIMARY KEY (version_id, image_id)
);
CREATE INDEX idx_editor_image_version_image ON editor_image_version_reference(image_id);
CREATE TRIGGER touch_editor_image_version AFTER INSERT OR DELETE ON editor_image_version_reference
FOR EACH ROW EXECUTE FUNCTION touch_editor_image_reference();
