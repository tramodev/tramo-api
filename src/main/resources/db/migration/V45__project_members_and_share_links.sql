CREATE TABLE project_share_link (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL UNIQUE,
    role varchar(16) NOT NULL CHECK (role IN ('EDITOR','VIEWER')),
    created_by bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamp NOT NULL,
    expires_at timestamp,
    revoked_at timestamp,
    last_used_at timestamp,
    use_count int NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_project_share_link_active ON project_share_link(project_id, role) WHERE revoked_at IS NULL;

CREATE TABLE project_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role varchar(16) NOT NULL CHECK (role IN ('EDITOR','VIEWER')),
    invited_by bigint REFERENCES users(id) ON DELETE SET NULL,
    share_link_id bigint REFERENCES project_share_link(id) ON DELETE SET NULL,
    created_at timestamp NOT NULL,
    UNIQUE (project_id, user_id)
);
CREATE INDEX idx_project_member_user ON project_member(user_id);
CREATE INDEX idx_project_member_share_link ON project_member(share_link_id);
